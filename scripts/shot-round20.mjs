import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
const ROOT = process.env.HOME + "/workspace/bnt-topup";
const CHS = process.env.HOME + "/workspace/tools/pptr-browsers/chrome-headless-shell/linux-157.0.8103.78/chrome-headless-shell-linux64/chrome-headless-shell";
const BASE = "http://127.0.0.1:3107";
const chrome = spawn(CHS, ["--headless", "--disable-gpu", "--no-sandbox", "--remote-debugging-port=9253", "--window-size=1440,1100", "about:blank"], { stdio: "ignore" });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await sleep(1500);
const targets = await (await fetch("http://127.0.0.1:9253/json")).json();
const ws = new WebSocket(targets[0].webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pending = new Map();
ws.onmessage = (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
await send("Page.enable"); await send("Runtime.enable");
await send("Page.navigate", { url: BASE + "/" }); await sleep(2300);
let r = await send("Page.captureScreenshot", { format: "png", captureBeyondViewport: false });
writeFileSync(`${ROOT}/shots/topup-home-nostats-1440.png`, Buffer.from(r.data, "base64"));
await send("Emulation.setDeviceMetricsOverride", { width: 390, height: 900, deviceScaleFactor: 1, mobile: true });
await sleep(500);
r = await send("Page.captureScreenshot", { format: "png", captureBeyondViewport: false });
writeFileSync(`${ROOT}/shots/topup-home-nostats-390.png`, Buffer.from(r.data, "base64"));
console.log("shots ok");
chrome.kill(); process.exit(0);
