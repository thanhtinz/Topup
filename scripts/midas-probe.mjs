import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
const CHROME = "/home/hatch/workspace/tools/pptr-browsers/chrome-headless-shell/linux-157.0.8103.78/chrome-headless-shell-linux64/chrome-headless-shell";
const PORT = 9317;
const proc = spawn(CHROME, ["--headless", "--disable-gpu", "--no-sandbox", `--remote-debugging-port=${PORT}`, "--window-size=1280,1000", "about:blank"], { stdio: "ignore" });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function wsUrl() { for (let i = 0; i < 40; i++) { try { const r = await fetch(`http://127.0.0.1:${PORT}/json/version`); const j = await r.json(); if (j.webSocketDebuggerUrl) return j.webSocketDebuggerUrl; } catch {} await sleep(300); } throw new Error("no ws"); }
const ws = new WebSocket(await wsUrl());
let id = 0; const pending = new Map();
ws.addEventListener("message", (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } });
await new Promise((r) => ws.addEventListener("open", r, { once: true }));
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
const { targetId } = await send("Target.createTarget", { url: "about:blank" });
const { sessionId } = await send("Target.attachToTarget", { targetId, flatten: true });
const S = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params, sessionId })); });
await S("Page.enable"); await S("Runtime.enable");
const url = process.argv[2];
const tag = process.argv[3] || "probe";
await S("Page.navigate", { url });
await sleep(9000);
await S("Runtime.evaluate", { expression: `window.scrollTo(0, 1200)` });
await sleep(2500);
await S("Runtime.evaluate", { expression: `window.scrollTo(0, 0)` });
await sleep(1500);
const res = await S("Runtime.evaluate", { expression: `JSON.stringify(performance.getEntriesByType('resource').map(r => ({n: r.name, t: r.initiatorType})))`, returnByValue: true });
const resources = JSON.parse(res.result?.value || "[]");
writeFileSync(`/tmp/midas-${tag}-resources.json`, JSON.stringify(resources, null, 1));
const dom = await S("Runtime.evaluate", { expression: `(() => { const main = document.querySelector('#app') || document.body; return main.innerHTML.slice(0, 60000); })()`, returnByValue: true });
writeFileSync(`/tmp/midas-${tag}-dom.html`, dom.result?.value || "");
console.log(tag, "resources:", resources.length, "| imgs:", resources.filter(r => /\.(png|jpg|jpeg|webp)/i.test(r.n)).length, "| xhr/fetch:", resources.filter(r => r.t === 'fetch' || r.t === 'xmlhttprequest').length);
proc.kill();
process.exit(0);
