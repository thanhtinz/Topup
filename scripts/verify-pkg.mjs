import { spawn, execFileSync } from "node:child_process";

const BASE = "http://127.0.0.1:3107";
const CHROME = process.env.HOME + "/workspace/tools/pptr-browsers/chrome-headless-shell/linux-157.0.8103.78/chrome-headless-shell-linux64/chrome-headless-shell";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const token = execFileSync("npx", ["tsx", "scripts/make-token.ts"], { cwd: process.env.HOME + "/workspace/bnt-topup", encoding: "utf8" }).trim();

const proc = spawn(CHROME, ["--headless", "--no-sandbox", "--remote-debugging-port=9336", "--window-size=1440,1000", "about:blank"], { stdio: "ignore" });
await sleep(1500);
const targets = await (await fetch("http://127.0.0.1:9336/json")).json();
const ws = new WebSocket(targets[0].webSocketDebuggerUrl);
await new Promise((res) => (ws.onopen = res));
let id = 0;
const pending = new Map();
ws.onmessage = (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
const ev = async (expr) => (await send("Runtime.evaluate", { expression: expr, returnByValue: true }))?.result?.value;

await send("Network.enable"); await send("Page.enable");
await send("Network.setCookie", { name: "bnttopup_session", value: token, url: BASE + "/", path: "/" });

const detailUrl = BASE + "/admin/games/1/packages";
console.log("trang quản lý gói:", detailUrl);
await send("Page.navigate", { url: detailUrl });
await sleep(2500);
const firstName = await ev(`document.querySelector('input[form="bulkPkgs"][name^="price_"]')?.name`);
const priceSel = `document.querySelector('input[name="${firstName}"]')`;
console.log("gói kiểm:", firstName);
const orig = await ev(`${priceSel}?.value`);
console.log("giá gốc gói đầu:", orig);
const testVal = (parseFloat(orig) + 1).toFixed(2);
await ev(`(() => { const el = ${priceSel}; el.focus(); document.execCommand('selectAll', false, null); document.execCommand('insertText', false, '${testVal}'); el.dispatchEvent(new Event('change', {bubbles:true})); return el.value; })()`);
await ev(`document.querySelector('button[form="bulkPkgs"]').click()`);
await sleep(3000);
console.log("thông báo sau lưu:", await ev(`document.querySelector('.msg-ok')?.textContent?.trim() ?? document.querySelector('.msg-err')?.textContent?.trim()`));
await send("Page.navigate", { url: detailUrl });
await sleep(2500);
console.log("giá sau reload:", await ev(`${priceSel}?.value`), "(mong đợi", testVal + ")");
await ev(`(() => { const el = ${priceSel}; el.focus(); document.execCommand('selectAll', false, null); document.execCommand('insertText', false, '${orig}'); return el.value; })()`);
await ev(`document.querySelector('button[form="bulkPkgs"]').click()`);
await sleep(3000);
await send("Page.navigate", { url: detailUrl });
await sleep(2500);
console.log("giá đã trả lại:", await ev(`${priceSel}?.value`), "(mong đợi", orig + ")");
const imgName = firstName.replace("price_", "img_");
const imgSel = `document.querySelector('input[name="${imgName}"]')`;
await ev(`(() => { const el = ${imgSel}; el.focus(); document.execCommand('selectAll', false, null); document.execCommand('insertText', false, '/covers/freefire.png'); return el.value; })()`);
await ev(`document.querySelector('button[form="bulkPkgs"]').click()`);
await sleep(3000);
await send("Page.navigate", { url: detailUrl });
await sleep(2500);
console.log("ảnh gói sau lưu + reload:", await ev(`${imgSel}?.value`), "(mong đợi /covers/freefire.png)");
await ev(`(() => { const el = ${imgSel}; el.focus(); document.execCommand('selectAll', false, null); document.execCommand('insertText', false, ''); return el.value; })()`);
await ev(`document.querySelector('button[form="bulkPkgs"]').click()`);
await sleep(3000);
await send("Page.navigate", { url: detailUrl });
await sleep(2500);
console.log("ảnh gói đã xoá lại:", JSON.stringify(await ev(`${imgSel}?.value`)), "(mong đợi rỗng)");
console.log("còn nút Làm tròn không:", await ev(`[...document.querySelectorAll('button')].some(b => b.textContent.includes('Làm tròn'))`), "(mong đợi false)");
