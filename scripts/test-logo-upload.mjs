import { spawn } from "node:child_process";
const CHROME = "/home/hatch/workspace/tools/pptr-browsers/chrome-headless-shell/linux-157.0.8103.78/chrome-headless-shell-linux64/chrome-headless-shell";
const PORT = 9297;
const proc = spawn(CHROME, ["--headless", "--disable-gpu", "--no-sandbox", `--remote-debugging-port=${PORT}`, "--window-size=1280,1000", "about:blank"], { stdio: "ignore" });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function wsUrl() { for (let i = 0; i < 40; i++) { try { const r = await fetch(`http://127.0.0.1:${PORT}/json/version`); const j = await r.json(); if (j.webSocketDebuggerUrl) return j.webSocketDebuggerUrl; } catch {} await sleep(300); } throw new Error("no ws"); }
const ws = new WebSocket(await wsUrl());
let id = 0; const pending = new Map();
ws.addEventListener("message", (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } });
await new Promise((r) => ws.addEventListener("open", r, { once: true }));
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
const { targetId } = await send("Target.createTarget", { url: "about:blank" });
const { sessionId } = await send("Target.attachToTarget", { targetId, flatten: true });
const S = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params, sessionId })); });
await S("Page.enable"); await S("Runtime.enable"); await S("Network.enable"); await S("DOM.enable");
await S("Network.setCookie", { name: "bnttopup_session", value: process.env.TOKEN, domain: "127.0.0.1", path: "/" });
await S("Page.navigate", { url: "http://127.0.0.1:3107/admin/website?tab=info" });
await sleep(2600);
const { root } = await S("DOM.getDocument", { depth: 1 });
const { nodeId } = await S("DOM.querySelector", { nodeId: root.nodeId, selector: 'input[name="logo"]' });
console.log("logo input node:", nodeId);
await S("DOM.setFileInputFiles", { nodeId, files: ["/tmp/test-logo-big.png"] });
await S("Runtime.evaluate", { expression: `[...document.querySelectorAll('button')].find(b => b.textContent.includes('Lưu cấu hình'))?.click()` });
await sleep(4500);
const state = await S("Runtime.evaluate", { expression: `JSON.stringify({ url: location.href, toast: document.querySelector('[role="status"]')?.textContent || '', preview: !!document.querySelector('img[alt="Logo hiện tại"]') })`, returnByValue: true });
console.log("sau luu:", state.result.value);
await S("Page.navigate", { url: "http://127.0.0.1:3107/" });
await sleep(2600);
const home = await S("Runtime.evaluate", { expression: `JSON.stringify({ brandLogo: !!document.querySelector('img.brand-logo'), accent: getComputedStyle(document.documentElement).getPropertyValue('--accent').trim() })`, returnByValue: true });
console.log("trang chu:", home.result.value);
ws.close(); proc.kill();
