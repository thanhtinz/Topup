import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
const ROOT = process.env.HOME + "/workspace/bnt-topup";
const CHS = process.env.HOME + "/workspace/tools/pptr-browsers/chrome-headless-shell/linux-157.0.8103.78/chrome-headless-shell-linux64/chrome-headless-shell";
const BASE = "http://127.0.0.1:3107";
const chrome = spawn(CHS, ["--headless", "--disable-gpu", "--no-sandbox", "--remote-debugging-port=9247", "--window-size=1440,1100", "about:blank"], { stdio: "ignore" });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await sleep(1500);
const targets = await (await fetch("http://127.0.0.1:9247/json")).json();
const ws = new WebSocket(targets[0].webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pending = new Map();
ws.onmessage = (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
await send("Page.enable"); await send("Runtime.enable");
await send("Page.navigate", { url: BASE + "/" }); await sleep(2300);
await send("Runtime.evaluate", { expression: `[...document.querySelectorAll('button')].find(e => e.textContent.trim() === 'Đăng nhập')?.click()` });
await sleep(1100);
const r = await send("Page.captureScreenshot", { format: "png", captureBeyondViewport: false });
writeFileSync(`${ROOT}/shots/topup-auth-popup-v9-social.png`, Buffer.from(r.data, "base64"));
console.log("shot popup v9");
chrome.kill(); process.exit(0);
