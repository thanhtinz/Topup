import { spawn } from "node:child_process";
const CHROME = "/home/hatch/workspace/tools/pptr-browsers/chrome-headless-shell/linux-157.0.8103.78/chrome-headless-shell-linux64/chrome-headless-shell";
const PORT = 9301;
const proc = spawn(CHROME, ["--headless", "--disable-gpu", "--no-sandbox", `--remote-debugging-port=${PORT}`, "--window-size=390,780", "about:blank"], { stdio: "ignore" });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function wsUrl() { for (let i = 0; i < 40; i++) { try { const r = await fetch(`http://127.0.0.1:${PORT}/json/version`); const j = await r.json(); if (j.webSocketDebuggerUrl) return j.webSocketDebuggerUrl; } catch {} await sleep(300); } throw new Error("no ws"); }
const ws = new WebSocket(await wsUrl());
let id = 0; const pending = new Map();
ws.addEventListener("message", (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } });
await new Promise((r) => ws.addEventListener("open", r, { once: true }));
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
const { targetId } = await send("Target.createTarget", { url: "about:blank" });
const { sessionId } = await send("Target.attachToTarget", { targetId, flatten: true });
const S = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params, sessionId })); });
await S("Page.enable"); await S("Runtime.enable"); await S("Network.enable");
await S("Network.setCookie", { name: "bnttopup_session", value: process.env.TOKEN, domain: "127.0.0.1", path: "/" });
await S("Page.navigate", { url: "http://127.0.0.1:3107/admin" });
await sleep(2800);
const ev = async (expr) => { const r = await S("Runtime.evaluate", { expression: expr, returnByValue: true }); return r.result.value; };
console.log("truoc:", await ev(`document.querySelector('.admin-shell').className`));
await ev(`document.querySelector('.admin-burger').click()`);
await sleep(400);
console.log("sau mo:", await ev(`document.querySelector('.admin-shell').className`));
await S("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: 350, y: 400, id: 1 }] });
await S("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
await sleep(400);
console.log("sau cham ngoai:", await ev(`document.querySelector('.admin-shell').className`));
await ev(`document.querySelector('.admin-burger').click()`);
await sleep(300);
await ev(`document.querySelector('.admin-side a').click()`);
await sleep(600);
console.log("sau bam muc menu:", await ev(`document.querySelector('.admin-shell').className`));
